"""Tests for the Codex host projection.

Encodes VAL-HOST-009..012: the exact Codex file set (shared .agents/skills
payload plus agents/openai.yaml policy files, .codex/agents/sf-*.toml,
.codex/hooks.json, one AGENTS.md managed block, the runtime helper set) with
no foreign-host artifacts, TOML agents with required keys and model omitted,
the explicit-only openai.yaml matrix, and the documented hooks.json shape.
Golden files in tests/goldens/codex/ pin the generated bytes.
"""
from __future__ import annotations

import importlib.util
import json
import re
import shutil
import tempfile
import tomllib
import unittest
from pathlib import Path

_spec = importlib.util.spec_from_file_location(
    "sf_test_support", Path(__file__).resolve().parent / "support.py"
)
support = importlib.util.module_from_spec(_spec)
_spec.loader.exec_module(support)

_spec = importlib.util.spec_from_file_location(
    "sf_validate", support.REPO / "scripts" / "validate.py"
)
validate = importlib.util.module_from_spec(_spec)
_spec.loader.exec_module(validate)

GOLDENS = support.REPO / "tests" / "goldens" / "codex"
EXPLICIT_ONLY = {
    "software-factory",
    "sf-help",
    "sf-agents",
    "sf-evolve",
    "sf-eval",
    "sf-principles",
}
WORKING_WITH_POLICY = {"sf-crawl"}


def canonical_tree():
    files = set()
    for path in sorted((support.REPO / "skills").rglob("*")):
        if not path.is_file():
            continue
        if "__pycache__" in path.parts or path.suffix == ".pyc":
            continue
        files.add(path.relative_to(support.REPO / "skills").as_posix())
    return files


def canonical_agent_body(name):
    """The canonical role body, normalized like the installer normalizes it."""
    text = (support.REPO / "agents" / f"{name}.md").read_text(encoding="utf-8")
    _, body = validate.split_frontmatter(text, support.REPO / "agents" / name)
    return body.lstrip("\n").rstrip("\n") + "\n"


class CodexInstallCase(unittest.TestCase):
    def setUp(self):
        self.temp = Path(tempfile.mkdtemp(prefix="sf-host-codex-")).resolve()
        self.addCleanup(shutil.rmtree, self.temp, ignore_errors=True)
        self.env, self.records, self.guard_log = support.recorder_env()
        self.home, _ = support.home_sentinel(self.temp)
        self.env["HOME"] = str(self.home)
        self.env.pop("CURSOR_VERSION", None)
        self.env.pop("CURSOR_PROJECT_DIR", None)

    def install(self, repo, *args):
        result = support.run_installer(
            "install", "--project", repo, "--host", "codex", *args, env=self.env
        )
        assert result.returncode == 0, result.stderr
        return result

    def install_fresh(self):
        repo = support.fresh_repo(self.temp)
        self.install(repo, "--skip-bmad")
        return repo


class FileSetTests(CodexInstallCase):
    def test_exact_codex_file_set_and_no_foreign_artifacts(self):
        repo = self.install_fresh()
        skills_dir = repo / ".agents/skills"
        names = sorted(p.name for p in skills_dir.iterdir() if p.is_dir())
        self.assertEqual(sorted(validate.SKILLS), names)
        # The mirrored tree plus the Codex policy files, nothing else.
        projected = {
            path.relative_to(skills_dir).as_posix()
            for path in sorted(skills_dir.rglob("*"))
            if path.is_file()
        }
        policies = {
            f"{skill}/agents/openai.yaml"
            for skill in sorted(EXPLICIT_ONLY | WORKING_WITH_POLICY)
        }
        self.assertEqual(canonical_tree() | policies, projected)
        # Eleven TOML agents, hooks.json, runtime helpers, one AGENTS.md block.
        agents = sorted(p.name for p in (repo / ".codex/agents").glob("sf-*.toml"))
        self.assertEqual([f"{n}.toml" for n in sorted(validate.AGENTS)], agents)
        self.assertTrue((repo / ".codex/hooks.json").is_file())
        runtime = sorted(
            p.name for p in (repo / ".software-factory/runtime").glob("*.py")
        )
        self.assertEqual(["config.py", "gate.py", "hook.py", "state.py"], runtime)
        agents_md = (repo / "AGENTS.md").read_text()
        self.assertEqual(1, agents_md.count("<!-- software-factory:begin -->"))
        self.assertEqual(1, agents_md.count("<!-- software-factory:end -->"))
        # No foreign-host artifacts.
        for absent in (".claude", ".cursor", "CLAUDE.md"):
            self.assertFalse((repo / absent).exists(), absent)

    def test_codex_only_leaves_user_files_byte_identical(self):
        repo = support.existing_repo(self.temp)
        self.install(repo, "--skip-bmad")
        self.assertEqual(
            support.CLAUDE_SETTINGS_FIXTURE,
            (repo / ".claude/settings.json").read_text(),
        )
        self.assertEqual(
            support.CURSOR_HOOKS_FIXTURE,
            (repo / ".cursor/hooks.json").read_text(),
        )
        self.assertEqual(
            "# My Project\n\nHouse rules: keep diffs small and tested.\n",
            (repo / "CLAUDE.md").read_text(),
        )
        # AGENTS.md gains exactly one managed block; user text survives.
        agents_md = (repo / "AGENTS.md").read_text()
        self.assertIn("# Notes\n\nWater the tests.\n", agents_md)
        self.assertEqual(1, agents_md.count("<!-- software-factory:begin -->"))


class TomlAgentTests(CodexInstallCase):
    def test_toml_agents_preserve_intent_and_inherit_permissions_and_model(self):
        repo = self.install_fresh()
        for name in sorted(validate.AGENTS):
            with self.subTest(agent=name):
                path = repo / ".codex/agents" / f"{name}.toml"
                data = tomllib.loads(path.read_text())
                self.assertEqual(name, data["name"])
                self.assertTrue(data["description"].strip())
                self.assertTrue(data["developer_instructions"].strip())
                # Only supported identity/instruction fields are emitted.
                # TOML parsing is format proof, never isolation/runtime proof.
                self.assertEqual(
                    {"name", "description", "developer_instructions"}, set(data)
                )
                self.assertNotIn("sandbox_mode", data)
                self.assertNotIn("model", data)
                self.assertIn("Permissions inherit the parent session", path.read_text())
                # The instructions are the canonical role body verbatim.
                self.assertEqual(
                    canonical_agent_body(name), data["developer_instructions"]
                )
                # No line in the file may look like a model assignment.
                self.assertIsNone(
                    re.search(r"(?m)^model", path.read_text()), name
                )

    def test_installer_reports_inheritance_without_claiming_live_loading(self):
        repo = support.fresh_repo(self.temp)
        result = self.install(repo, "--skip-bmad")
        self.assertIn("inherit parent permissions", result.stdout)
        self.assertIn("Live custom-agent loading is unverified", result.stdout)
        pointer = (repo / "AGENTS.md").read_text()
        self.assertIn("instructions do not enforce a separate read-only sandbox", pointer)
        self.assertIn("verify an actually read-only parent/session", pointer)

    def test_codex_only_skills_preserve_canonical_bytes(self):
        repo = self.install_fresh()
        for rel in canonical_tree():
            self.assertEqual(
                (support.REPO / "skills" / rel).read_bytes(),
                (repo / ".agents/skills" / rel).read_bytes(), rel,
            )


class OpenaiYamlTests(CodexInstallCase):
    def test_explicit_only_matrix(self):
        repo = self.install_fresh()
        skills_dir = repo / ".agents/skills"
        for skill in sorted(EXPLICIT_ONLY):
            with self.subTest(skill=skill):
                path = skills_dir / skill / "agents/openai.yaml"
                self.assertTrue(path.is_file(), skill)
                text = path.read_text()
                self.assertEqual(
                    1, text.count("allow_implicit_invocation: false")
                )
                self.assertIn("policy:", text)
        crawl = (skills_dir / "sf-crawl/agents/openai.yaml").read_text()
        self.assertIn("allow_implicit_invocation: true", crawl)
        self.assertNotIn("allow_implicit_invocation: false", crawl)
        # Design skills stay implicit and carry no policy file at all.
        for skill in ("sf-design", "sf-smell-audit", "sf-refactor",
                      "sf-patterns"):
            with self.subTest(skill=skill):
                self.assertFalse(
                    (skills_dir / skill / "agents/openai.yaml").exists()
                )

    def test_openai_yaml_matches_goldens(self):
        repo = self.install_fresh()
        pairs = [
            ("software-factory", "openai/software-factory.yaml"),
            ("sf-crawl", "openai/sf-crawl.yaml"),
        ]
        for skill, golden in pairs:
            with self.subTest(skill=skill):
                expected = (GOLDENS / golden).read_bytes()
                actual = repo / f".agents/skills/{skill}/agents/openai.yaml"
                self.assertEqual(expected, actual.read_bytes())


class CodexHookTests(CodexInstallCase):
    def owned_commands(self, repo, event):
        doc = json.loads((repo / ".codex/hooks.json").read_text())
        return doc, [
            handler["command"]
            for group in doc["hooks"][event]
            for handler in group["hooks"]
            if "runtime/hook.py" in str(handler.get("command", ""))
        ]

    def test_hooks_json_shape_and_matchers(self):
        repo = self.install_fresh()
        doc = json.loads((repo / ".codex/hooks.json").read_text())
        for event, sources in (
            ("SessionStart", ("startup", "resume", "clear", "compact")),
            ("PreCompact", ("manual", "auto")),
        ):
            with self.subTest(event=event):
                groups = doc["hooks"][event]
                self.assertIsInstance(groups, list)
                owned = [
                    group
                    for group in groups
                    if any(
                        "runtime/hook.py" in str(h.get("command", ""))
                        for h in group["hooks"]
                    )
                ]
                self.assertEqual(1, len(owned))
                for source in sources:
                    self.assertRegex(source, owned[0]["matcher"])
                handler = owned[0]["hooks"][0]
                self.assertEqual("command", handler["type"])
                command = handler["command"]
                self.assertIn("--host codex", command)
                self.assertIn("--event", command)
                self.assertTrue(command.rstrip().endswith("2>&1"))
        raw = (repo / ".codex/hooks.json").read_text()
        self.assertEqual(2, len(re.findall(r'"type":\s*"command"', raw)))

    def test_hooks_merge_preserves_user_groups(self):
        repo = support.fresh_repo(self.temp)
        hooks = repo / ".codex/hooks.json"
        hooks.parent.mkdir()
        user_group = {
            "matcher": "startup",
            "hooks": [{"type": "command", "command": "echo user-start"}],
        }
        hooks.write_text(
            json.dumps({"hooks": {"SessionStart": [user_group]}}) + "\n"
        )
        self.install(repo, "--skip-bmad")
        doc = json.loads(hooks.read_text())
        self.assertIn(user_group, doc["hooks"]["SessionStart"])
        _, owned = self.owned_commands(repo, "SessionStart")
        self.assertEqual(1, len(owned))
        # A rerun adds no duplicates and is a byte-level no-op.
        before = hooks.read_bytes()
        again = support.run_installer(
            "install", "--project", repo, "--host", "codex", "--skip-bmad",
            env=self.env,
        )
        self.assertEqual(0, again.returncode, again.stderr)
        self.assertIn("0 changes", again.stdout)
        self.assertEqual(before, hooks.read_bytes())


