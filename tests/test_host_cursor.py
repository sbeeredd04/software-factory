"""Tests for the Cursor host projection.

Encodes VAL-HOST-005..008: the exact Cursor file set (shared .agents/skills
payload with explicit invocation frontmatter, .cursor/agents/sf-*.md, .cursor/hooks.json
v1, .cursor/rules/software-factory.mdc, the runtime helper set) with no
foreign-host artifacts, the hooks.json v1 non-destructive merge, the readonly
agent matrix from hosts/cursor/agent-policy.json, and the short always-applied
rule pointer. Golden files in tests/goldens/cursor/ pin the generated bytes.
"""
from __future__ import annotations

import importlib.util
import json
import shutil
import tempfile
import unittest
from pathlib import Path

_spec = importlib.util.spec_from_file_location(
    "sf_test_support", Path(__file__).resolve().parent / "support.py"
)
support = importlib.util.module_from_spec(_spec)
_spec.loader.exec_module(support)

_spec = importlib.util.spec_from_file_location(
    "sf_validate", support.REPO / "scripts" / "validate.py"
)
validate = importlib.util.module_from_spec(_spec)
_spec.loader.exec_module(validate)

GOLDENS = support.REPO / "tests" / "goldens" / "cursor"
EXPLICIT_ONLY = {
    "software-factory", "sf-help", "sf-agents", "sf-evolve", "sf-eval", "sf-principles",
}
READONLY_ROLES = {
    "sf-code-reviewer",
    "sf-design-reviewer",
    "sf-evaluator",
    "sf-security-reviewer",
}
WRITABLE_ROLES = {"sf-engineer", "sf-principal-engineer", "sf-qa-engineer"}


def canonical_tree():
    files = set()
    for path in sorted((support.REPO / "skills").rglob("*")):
        if not path.is_file():
            continue
        if "__pycache__" in path.parts or path.suffix == ".pyc":
            continue
        files.add(path.relative_to(support.REPO / "skills").as_posix())
    return files


class CursorInstallCase(unittest.TestCase):
    host_args = ("--host", "cursor")

    def setUp(self):
        self.temp = Path(tempfile.mkdtemp(prefix="sf-host-cursor-")).resolve()
        self.addCleanup(shutil.rmtree, self.temp, ignore_errors=True)
        self.env, self.records, self.guard_log = support.recorder_env()
        self.home, _ = support.home_sentinel(self.temp)
        self.env["HOME"] = str(self.home)
        self.env.pop("CURSOR_VERSION", None)
        self.env.pop("CURSOR_PROJECT_DIR", None)

    def install(self, repo, *args):
        result = support.run_installer(
            "install", "--project", repo, *self.host_args, *args, env=self.env
        )
        assert result.returncode == 0, result.stderr
        return result

    def install_fresh(self):
        repo = support.fresh_repo(self.temp)
        self.install(repo, "--skip-bmad")
        return repo

    def hook_entries(self, repo, event):
        doc = json.loads((repo / ".cursor/hooks.json").read_text())
        return doc, [
            entry
            for entry in doc["hooks"].get(event, [])
            if "runtime/hook.py" in str(entry.get("command", ""))
        ]


class FileSetTests(CursorInstallCase):
    def test_exact_cursor_file_set_and_no_foreign_artifacts(self):
        repo = self.install_fresh()
        # Shared skills payload: the eleven skills, mirrored one-to-one.
        skills_dir = repo / ".agents/skills"
        self.assertTrue((skills_dir / "software-factory").is_dir())
        projected = {
            path.relative_to(skills_dir).as_posix()
            for path in sorted(skills_dir.rglob("*"))
            if path.is_file()
        }
        self.assertEqual(canonical_tree(), projected)
        # Eleven role agents, hooks v1, the rule pointer, runtime helpers.
        agents = sorted(p.name for p in (repo / ".cursor/agents").glob("sf-*.md"))
        self.assertEqual([f"{n}.md" for n in sorted(validate.AGENTS)], agents)
        self.assertTrue((repo / ".cursor/hooks.json").is_file())
        self.assertTrue((repo / ".cursor/rules/software-factory.mdc").is_file())
        runtime = sorted(
            p.name for p in (repo / ".software-factory/runtime").glob("*.py")
        )
        self.assertEqual(["config.py", "gate.py", "hook.py", "state.py"], runtime)
        # No foreign-host artifacts, no managed-block pointers.
        for absent in (".claude", ".codex", "CLAUDE.md", "AGENTS.md"):
            self.assertFalse((repo / absent).exists(), absent)
        # A Cursor-only install carries no Codex skill policy files.
        self.assertEqual([], list(skills_dir.rglob("openai.yaml")))

    def test_only_entry_admin_skills_gain_explicit_invocation_frontmatter(self):
        sources = {
            rel: (support.REPO / "skills" / rel).read_bytes()
            for rel in canonical_tree()
        }
        repo = self.install_fresh()
        for rel, canonical in sorted(sources.items()):
            with self.subTest(path=rel):
                projected = repo / ".agents/skills" / rel
                raw = projected.read_text()
                self.assertNotIn("argument-hint:", raw)
                if Path(rel).name == "SKILL.md" and Path(rel).parts[0] in EXPLICIT_ONLY:
                    meta = validate.parse_frontmatter(raw, projected)
                    self.assertEqual("true", meta["disable-model-invocation"])
                    self.assertEqual(1, raw.count("disable-model-invocation: true\n"))
                    raw = raw.replace("disable-model-invocation: true\n", "", 1)
                else:
                    self.assertNotIn("disable-model-invocation:", raw)
                self.assertEqual(canonical, raw.encode(), rel)
                self.assertEqual(canonical, (support.REPO / "skills" / rel).read_bytes())


class HookMergeTests(CursorInstallCase):
    def test_hooks_v1_merge_preserves_user_entries(self):
        repo = support.existing_repo(self.temp)
        self.install(repo, "--skip-bmad")
        doc = json.loads((repo / ".cursor/hooks.json").read_text())
        self.assertEqual(1, doc["version"])
        fixture = json.loads(support.CURSOR_HOOKS_FIXTURE)
        self.assertEqual(
            fixture["hooks"]["beforeShellExecution"],
            doc["hooks"]["beforeShellExecution"],
        )
        for event, normalized in (("sessionStart", "session-start"),
                                  ("preCompact", "pre-compact")):
            with self.subTest(event=event):
                _, owned = self.hook_entries(repo, event)
                self.assertEqual(1, len(owned))
                self.assertNotIn("matcher", owned[0])
                command = owned[0]["command"]
                self.assertIn("runtime/hook.py", command)
                self.assertIn("--host cursor", command)
                self.assertIn(f"--event {normalized}", command)
                # stderr merges into stdout (VAL-HOST-018).
                self.assertTrue(command.rstrip().endswith("2>&1"))

    def test_second_install_adds_no_duplicate_entries(self):
        repo = support.existing_repo(self.temp)
        self.install(repo, "--skip-bmad")
        before = (repo / ".cursor/hooks.json").read_bytes()
        again = support.run_installer(
            "install", "--project", repo, "--host", "cursor", "--skip-bmad",
            env=self.env,
        )
        self.assertEqual(0, again.returncode, again.stderr)
        self.assertIn("0 changes", again.stdout)
        self.assertEqual(before, (repo / ".cursor/hooks.json").read_bytes())
        for event in ("sessionStart", "preCompact"):
            _, owned = self.hook_entries(repo, event)
            self.assertEqual(1, len(owned))

    def test_malformed_hooks_json_is_refused_without_writes(self):
        repo = support.fresh_repo(self.temp)
        hooks = repo / ".cursor/hooks.json"
        hooks.parent.mkdir()
        hooks.write_text('{"version": 1, "hooks":')
        before = support.tree_hashes(repo)
        result = support.run_installer(
            "install", "--project", repo, "--host", "cursor", "--skip-bmad",
            env=self.env,
        )
        self.assertEqual(1, result.returncode)
        self.assertIn("hooks.json", result.stderr)
        self.assertEqual(before, support.tree_hashes(repo))

    def test_foreign_hooks_version_is_refused_without_writes(self):
        repo = support.fresh_repo(self.temp)
        hooks = repo / ".cursor/hooks.json"
        hooks.parent.mkdir()
        hooks.write_text('{"version": 2, "hooks": {}}\n')
        before = support.tree_hashes(repo)
        result = support.run_installer(
            "install", "--project", repo, "--host", "cursor", "--skip-bmad",
            env=self.env,
        )
        self.assertEqual(1, result.returncode)
        self.assertIn("version", result.stderr)
        self.assertEqual(before, support.tree_hashes(repo))


class AgentReadonlyTests(CursorInstallCase):
    def test_readonly_matrix_matches_host_policy(self):
        repo = self.install_fresh()
        policy = json.loads(
            (support.REPO / "hosts/cursor/agent-policy.json").read_text()
        )
        readonly = set(policy["readonly"])
        # The pinned roles from VAL-HOST-007 are present in the policy.
        self.assertTrue(READONLY_ROLES <= readonly)
        self.assertFalse(readonly & WRITABLE_ROLES)
        for name in sorted(validate.AGENTS):
            with self.subTest(agent=name):
                path = repo / ".cursor/agents" / f"{name}.md"
                meta = validate.parse_frontmatter(path.read_text(), path)
                self.assertEqual(name, meta["name"])
                self.assertEqual("inherit", meta["model"])
                self.assertNotIn("isolation", meta)
                expected = "true" if name in readonly else "false"
                self.assertEqual(expected, meta["readonly"])

    def test_readonly_true_exactly_for_reviewer_evaluator_roles(self):
        repo = self.install_fresh()
        flagged = set()
        for path in (repo / ".cursor/agents").glob("sf-*.md"):
            raw = path.read_text()
            self.assertNotIn("bypassPermissions", raw)
            if "readonly: true" in raw:
                flagged.add(path.stem)
        self.assertEqual(READONLY_ROLES, flagged)


class RulePointerTests(CursorInstallCase):
    def test_rule_is_short_always_applied_and_points_at_the_skill(self):
        repo = self.install_fresh()
        rule = repo / ".cursor/rules/software-factory.mdc"
        meta = validate.parse_frontmatter(rule.read_text(), rule)
        self.assertEqual("true", meta["alwaysApply"])
        self.assertIsInstance(meta["description"], str)
        self.assertTrue(meta["description"].strip())
        body = meta["__body__"]
        self.assertIn(".agents/skills/software-factory/", body)
        lines = rule.read_text().splitlines()
        self.assertLessEqual(len(lines), 60)
        orchestrator = support.REPO / "skills/software-factory/SKILL.md"
        self.assertLess(
            len(lines), len(orchestrator.read_text().splitlines()) // 3
        )


class IsolationTests(CursorInstallCase):
    def test_cursor_only_leaves_user_host_files_byte_identical(self):
        repo = support.existing_repo(self.temp)
        self.install(repo, "--skip-bmad")
        # The Claude fixture and both user instruction files are untouched:
        # the Cursor pointer is the .mdc rule, never a managed block.
        self.assertEqual(
            support.CLAUDE_SETTINGS_FIXTURE,
            (repo / ".claude/settings.json").read_text(),
        )
        self.assertEqual(
            "# My Project\n\nHouse rules: keep diffs small and tested.\n",
            (repo / "CLAUDE.md").read_text(),
        )
        self.assertEqual("# Notes\n\nWater the tests.\n",
                         (repo / "AGENTS.md").read_text())
        self.assertFalse((repo / ".codex").exists())


class GoldenTests(CursorInstallCase):
    def test_projected_files_match_goldens(self):
        repo = self.install_fresh()
        pairs = [
            (".cursor/rules/software-factory.mdc", "software-factory.mdc"),
            (".cursor/agents/sf-code-reviewer.md", "agents/sf-code-reviewer.md"),
            (".cursor/agents/sf-engineer.md", "agents/sf-engineer.md"),
        ]
        for rel, golden in pairs:
            with self.subTest(golden=golden):
                expected = (GOLDENS / golden).read_bytes()
                self.assertEqual(expected, (repo / rel).read_bytes())


