def esc(value):
    return html.escape("" if value is None else str(value))


def short_sha(value):
    return esc(value[:12]) if value else ""


def badge(text, kind=""):
    return f'<span class="badge {kind}">{esc(text)}</span>'


def story_card(story):
    parts = [f'<div class="card" id="story-{story["id"]}">']
    parts.append(f'<div class="title">#{story["id"]} {esc(story["title"])}</div>')
    badges = [badge(story["type"])]
    if story.get("sprint"):
        badges.append(badge(f'sprint: {story["sprint"]}', "sprint"))
    if story.get("risk"):
        badges.append(badge(f'risk {story["risk"]}'))
    if story.get("blocked"):
        badges.append(badge(f'blocked: {story["blocked"]["type"]}', "blocked"))
    if story["status"] == "done":
        badges.append(badge("done", "done"))
    parts.append("<div>" + " ".join(badges) + "</div>")
    claim = story.get("claim") or {}
    owner = story.get("owner") or "unassigned"
    claim_line = f'claim: live ({esc(claim.get("owner"))})' if claim.get("live") else "claim: none"
    parts.append(f'<div class="small">owner: {esc(owner)} · {claim_line}</div>')
    if story.get("blocked"):
        blocked = story["blocked"]
        parts.append(
            f'<div class="small">blocked since {esc(blocked["since"])} — '
            f'{esc(blocked["reason"])} (owner: {esc(blocked["owner"])}; '
            f'next: {esc(blocked["next_action"])})</div>'
        )
    receipts = story.get("receipts") or {}
    if receipts:
        items = []
        for name, receipt in sorted(receipts.items()):
            sha = short_sha(receipt.get("subject_sha", ""))
            extra = receipt.get("result") or receipt.get("verdict") or ""
            suffix = f" · {esc(extra)}" if extra else ""
            items.append(f"<li>{esc(name)} <code>{sha}</code>{suffix}</li>")
        parts.append("<ul>" + "".join(items) + "</ul>")
    refs = []
    if story.get("pr"):
        refs.append(f'PR {esc(story["pr"])}')
    if story.get("merged_sha"):
        refs.append(f'merged <code>{esc(story["merged_sha"])}</code>')
    if story.get("baseline_sha"):
        refs.append(f'baseline <code>{short_sha(story["baseline_sha"])}</code>')
    if story.get("branch"):
        refs.append(f'branch {esc(story["branch"])}')
    if refs:
        parts.append('<div class="small">' + " · ".join(refs) + "</div>")
    history = story.get("history") or []
    findings = story.get("findings") or []
    if history or findings:
        rows = "".join(
            f"<li>{esc(row['at'])} — {esc(row['by'])}: {esc(row.get('from'))} → "
            f"{esc(row['to'])}</li>"
            for row in reversed(history)
        )
        notes = "".join(
            f"<li>{esc(item['at'])} — {esc(item.get('by', ''))}: {esc(item['text'])}</li>"
            for item in reversed(findings)
        )
        parts.append(
            f"<details><summary>history ({len(history)})</summary><ul>{rows}{notes}</ul></details>"
        )
    parts.append("</div>")
    return "".join(parts)


def render_streams(roadmap):
    stories_by_stream = {}
    for story in roadmap["stories"]:
        stories_by_stream.setdefault(story["stream"], []).append(story)
    out = ['<section id="streams"><h2>Streams</h2>']
    for stream in roadmap["streams"]:
        counts = stream["counts"]
        summary = " · ".join(f"{name}: {counts.get(name, 0)}" for name in ALL_STATES)
        out.append(
            f'<div class="stream" id="stream-{esc(stream["id"])}">'
            f'<h3>{esc(stream["id"])} — {esc(stream["title"])} '
            f'{badge(stream["status"])}</h3>'
            f'<div class="small">{esc(summary)}</div>'
        )
        lanes = []
        for column in COLUMNS:
            cards = [
                story_card(story)
                for story in stories_by_stream.get(stream["id"], [])
                if story["state"] == column
            ]
            body = "".join(cards) if cards else '<div class="empty">none</div>'
            lanes.append(f'<div class="lane"><h4>{esc(column)}</h4>{body}</div>')
        out.append('<div class="lanes">' + "".join(lanes) + "</div>")
        rest = [
            story for story in stories_by_stream.get(stream["id"], [])
            if story["state"] in ("planned", "cancelled")
        ]
        if rest:
            rows = "".join(
                f"<tr><td>#{story['id']}</td><td>{esc(story['title'])}</td>"
                f"<td>{esc(story['state'])}</td><td>{esc(story['status'])}</td></tr>"
                for story in rest
            )
            out.append(
                "<details><summary>planned / cancelled</summary>"
                f"<table><tr><th>id</th><th>title</th><th>state</th><th>status</th></tr>"
                f"{rows}</table></details>"
            )
        out.append("</div>")
    out.append("</section>")
    return "".join(out)


def render_frontier(roadmap):
    ready = roadmap["frontier"]["ready"]
    waiting = roadmap["frontier"]["waiting_on_prereq"]
    out = ['<section id="frontier"><h2>Ready now</h2>']
    if ready:
        rows = "".join(
            f"<tr><td>#{entry['id']}</td><td>{esc(entry['title'])}</td>"
            f"<td>{esc(entry['stream'])}</td><td>{esc(entry['why'])}</td><td>unclaimed</td></tr>"
            for entry in ready
        )
        out.append(
            "<table><tr><th>id</th><th>story</th><th>stream</th>"
            f"<th>why ready</th><th>claim</th></tr>{rows}</table>"
        )
    else:
        out.append('<div class="empty">nothing ready to claim</div>')
    if waiting:
        rows = "".join(
            f"<tr><td>#{entry['id']}</td><td>{esc(entry['title'])}</td>"
            f"<td>{esc(entry['stream'])}</td><td>{esc('; '.join(entry['missing']))}</td></tr>"
            for entry in waiting
        )
        out.append(
            "<h3>Waiting on prerequisites</h3>"
            "<table><tr><th>id</th><th>story</th><th>stream</th>"
            f"<th>missing</th></tr>{rows}</table>"
        )
    out.append("</section>")
    return "".join(out)


def render_blockers(roadmap):
    out = ['<section id="blockers"><h2>Blockers</h2>']
    blockers = roadmap["blockers"]
    if not blockers:
        out.append('<div class="empty">no blockers</div></section>')
        return "".join(out)
    grouped = {}
    for blocker in blockers:
        grouped.setdefault(blocker["type"], []).append(blocker)
    for kind in sorted(grouped):
        out.append(f"<h3>{esc(kind)}</h3><ul>")
        for blocker in grouped[kind]:
            stalls = ", ".join(f"#{item}" for item in blocker["stalls"]) or "nothing downstream"
            out.append(
                f"<li><strong>#{blocker['id']}</strong> ({esc(blocker['stream'] or '')}) — "
                f"{esc(blocker['reason'])} · owner: {esc(blocker['owner'])} · "
                f"since {esc(blocker['since'])} · next: {esc(blocker['next_action'])} · "
                f"stalls: {esc(stalls)}</li>"
            )
        out.append("</ul>")
    out.append("</section>")
    return "".join(out)


def render_acceptance(roadmap):
    out = ['<section id="acceptance"><h2>Epic acceptance</h2>']
    if not roadmap["epics"]:
        out.append('<div class="empty">no epics</div></section>')
        return "".join(out)
    for epic in roadmap["epics"]:
        items = "".join(f"<li>{esc(item)}</li>" for item in epic["done_when"]) or "<li>—</li>"
        extra = ""
        if epic.get("parked"):
            extra = f'<div class="small">parked — resume: {esc(epic["parked"].get("resume", ""))}</div>'
        out.append(
            f"<h3>Epic {epic['id']} — {esc(epic['title'])} {badge(epic['status'])}</h3>"
            f'<div class="small">stream {esc(epic["stream"])} · outcome: {esc(epic["outcome"])}</div>'
            f"<ul>{items}</ul>{extra}"
        )
    out.append("</section>")
    return "".join(out)


def _detail_list(items, render, empty):
    if not items:
        return f'<div class="empty">{esc(empty)}</div>'
    return "<ul>" + "".join(f"<li>{esc(render(item))}</li>" for item in items) + "</ul>"


def render_diagnostics(roadmap):
    diag = roadmap["diagnostics"]
    out = ['<section id="diagnostics"><h2>Diagnostics</h2>']
    out.append("<h3>Unpinned epic gates</h3>")
    out.append(_detail_list(diag["unpinned_gates"], lambda d: d["detail"], "none"))
    out.append("<h3>Undeclared cross-stream dependencies</h3>")
    out.append(_detail_list(diag["undeclared_after"], lambda d: d["detail"], "none"))
    out.append("<h3>Order conflicts</h3>")
    out.append(_detail_list(diag["order_conflicts"], lambda d: d["detail"], "none"))
    out.append("<h3>Claim / record inconsistencies</h3>")
    out.append(_detail_list(diag["inconsistencies"], lambda d: d["detail"], "none"))
    out.append("</section>")
    return "".join(out)


def render_critical_path(roadmap):
    out = ['<section id="critical-path"><h2>Critical path per stream</h2>']
    rows = []
    for stream in roadmap["streams"]:
        chain = " → ".join(f"#{item}" for item in stream["critical_path"]) or "—"
        rows.append(f"<tr><td>{esc(stream['id'])}</td><td>{esc(chain)}</td></tr>")
    out.append(f"<table><tr><th>stream</th><th>longest remaining chain</th></tr>{''.join(rows)}</table>")
    out.append("</section>")
    return "".join(out)


def render_problems(roadmap):
    out = ['<section id="problems"><h2>Problems</h2>']
    problems = roadmap["problems"]
    if not problems:
        out.append('<div class="empty">no invalid records</div></section>')
        return "".join(out)
    rows = "".join(
        f"<tr><td>{esc(problem.get('file', ''))}</td><td>{esc(problem.get('reason', ''))}</td></tr>"
        for problem in problems
    )
    out.append(f"<table><tr><th>record</th><th>reason</th></tr>{rows}</table></section>")
    return "".join(out)


def render_decisions(roadmap):
    out = ['<section id="decisions"><h2>Decision queue</h2>']
    queue = roadmap["decision_queue"]
    if not queue:
        out.append('<div class="empty">nothing waits on a human</div></section>')
        return "".join(out)
    rows = "".join(
        f"<tr><td>{esc(entry['kind'])}</td><td>{esc(entry['question'])}</td>"
        f"<td>{esc(entry.get('next_action', ''))}</td></tr>"
        for entry in queue
    )
    out.append(
        f"<table><tr><th>kind</th><th>question</th><th>next action</th></tr>{rows}</table></section>"
    )
    return "".join(out)


def render_html(roadmap):
    """The whole dashboard as one deterministic, escaped, offline HTML string."""
    generated = roadmap.get("generated", {})
    command = generated.get("command", "python3 scripts/roadmap.py build --workspace <project-root>")
    body = "".join(
        [
            render_frontier(roadmap),
            render_streams(roadmap),
            render_blockers(roadmap),
            render_critical_path(roadmap),
            render_acceptance(roadmap),
            render_diagnostics(roadmap),
            render_problems(roadmap),
            render_decisions(roadmap),
        ]
    )
    return f"""<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>Software Factory board</title>
<!-- Generated by {esc(generated.get('by', 'roadmap.py build'))} — do not hand-edit. -->
<style>{STYLE}</style>
</head>
<body>
<header>
<h1>Software Factory board</h1>
<p class="meta">revision {roadmap.get("revision", 0)} · generated {esc(roadmap.get("generated_at", ""))} ·
{len(roadmap.get("stories", []))} stories across {len(roadmap.get("streams", []))} streams</p>
</header>
{body}
<footer>
Generated by {esc(generated.get("by", "roadmap.py build"))} from the per-story board
records — do not hand-edit. Regenerate: <code>{esc(command)}</code>.
The records under the board directory are the live story-status store; this page
is a locked, regenerable projection.
</footer>
</body>
</html>
"""


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--workspace", type=Path, default=Path.cwd())
    parser.add_argument("--board", type=Path, default=None)
    parser.add_argument("--out", type=Path, default=None)
    args = parser.parse_args()
    board = args.board or args.workspace.resolve() / ".software-factory" / "context" / "board"
    roadmap_path = board / "roadmap.json"
    try:
        roadmap = json.loads(roadmap_path.read_text())
    except (OSError, ValueError):
        print(
            "dashboard: no roadmap.json; run `roadmap.py build` first — the "
            "dashboard is a regenerable projection of the board records",
            file=sys.stderr,
        )
        return 2
    out = args.out or board / "dashboard.html"
    out.write_text(render_html(roadmap))
    print(f"dashboard: rendered {out}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
