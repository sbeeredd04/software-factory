"""Render the Software Factory board dashboard as one static offline HTML file.

`render_html(roadmap)` is a pure function of the generated roadmap.json
projection: stream swimlanes with counts, board columns, the cross-stream
ready frontier, the blockers panel, per-story receipts, the critical path
per stream, the epic done-when acceptance checklist, and the diagnostics,
problems and decision strips. No build step, no framework, no JavaScript, no
external font, style, script or image request — the file is a view-only
render, regenerated by `roadmap.py build` after every board update.
"""
from __future__ import annotations

import argparse
import html
import json
import sys
from pathlib import Path

COLUMNS = ["ready", "in-progress", "review", "built", "done"]
ALL_STATES = ["planned", *COLUMNS, "cancelled"]

